-- Versatile Rewards member portal (rewards.versatilestudios.com).
--
-- Customers sign in with a one-time email link sent to a rewards_contacts
-- address; there are no customer passwords and no Supabase auth users. The
-- link token and the session cookie are random secrets stored only as SHA-256
-- hashes. Only the service role touches these tables (no RLS policies = no
-- access through the anon/authenticated keys).

-- Member number shown to customers as VR-<n> (VR-100001, VR-100002, ...).
alter table rewards_members
  add column member_number bigint generated by default as identity (start with 100001);
create unique index rewards_members_member_number on rewards_members (member_number);

alter table rewards_contacts
  add column last_signed_in_at timestamptz;

-- Who asked for a redemption from the portal (staff requests keep created_by).
alter table rewards_redemptions
  add column requested_by_contact_id uuid references rewards_contacts(id) on delete set null;

-- When the customer has seen a tier change in the portal ("Tier Reached").
alter table rewards_tier_changes
  add column customer_seen_at timestamptz;

-- Monthly statement emails stay off until switched on in Rewards settings.
alter table rewards_programs
  add column statements_enabled boolean not null default false,
  add column last_statement_month text;

create table rewards_portal_tokens (
  id uuid primary key default gen_random_uuid(),
  token_hash text not null unique,
  contact_id uuid not null references rewards_contacts(id) on delete cascade,
  member_id uuid not null references rewards_members(id) on delete cascade,
  expires_at timestamptz not null,
  used_at timestamptz,
  requested_ip text,
  created_at timestamptz not null default now()
);
create index rewards_portal_tokens_contact on rewards_portal_tokens (contact_id, created_at);

create table rewards_portal_sessions (
  id uuid primary key default gen_random_uuid(),
  session_hash text not null unique,
  member_id uuid not null references rewards_members(id) on delete cascade,
  -- A customer session has a contact; a staff "View as Member" session has a
  -- staff user instead and is read-only.
  contact_id uuid references rewards_contacts(id) on delete cascade,
  staff_user_id uuid,
  include_preview boolean not null default false,
  expires_at timestamptz not null,
  last_seen_at timestamptz,
  created_at timestamptz not null default now(),
  check (contact_id is not null or staff_user_id is not null)
);
create index rewards_portal_sessions_member on rewards_portal_sessions (member_id);

alter table rewards_portal_tokens enable row level security;
alter table rewards_portal_sessions enable row level security;

